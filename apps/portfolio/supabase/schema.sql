-- Maintains updated_at on any table that has the column.
create or replace function public.tg_set_updated_at()
returns trigger
language plpgsql
security invoker
set search_path = ''
as $$
begin
  new.updated_at := timezone('utc', now());
  return new;
end;
$$;

-- Collapses whitespace, strips C0/C1 control characters, trims and hard-truncates.
-- Used to normalise every piece of untrusted text before it is stored.
create or replace function public.clean_text(value text, max_len integer default 512)
returns text
language sql
immutable
security invoker
set search_path = ''
as $$
  select nullif(
    left(
      btrim(regexp_replace(regexp_replace(value, '[\u0000-\u001F\u007F-\u009F]', ' ', 'g'), '\s+', ' ', 'g')),
      greatest(max_len, 1)
    ),
    ''
  );
$$;

