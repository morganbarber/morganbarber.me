-- Token-bucket limiter. Returns true when the call is allowed.
-- Not exposed to anon directly; only called from the functions below.
create or replace function public.consume_rate_limit(
  p_key       text,
  p_limit     integer,
  p_window    interval
)
returns boolean
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_now      timestamptz := timezone('utc', now());
  v_tokens   integer;
begin
  if p_key is null or p_limit <= 0 then
    return false;
  end if;

  insert into public.rate_limit_buckets as b (bucket_key, tokens, window_start, updated_at)
  values (left(p_key, 200), 1, v_now, v_now)
  on conflict (bucket_key) do update
    set tokens = case
          when b.window_start < v_now - p_window then 1
          else b.tokens + 1
        end,
        window_start = case
          when b.window_start < v_now - p_window then v_now
          else b.window_start
        end,
        updated_at = v_now
  returning b.tokens into v_tokens;

  return v_tokens <= p_limit;
end;
$$;

revoke all on function public.consume_rate_limit(text, integer, interval) from public, anon, authenticated;
revoke all on function public.clean_text(text, integer) from public, anon, authenticated;
revoke all on function public.tg_set_updated_at() from public, anon, authenticated;

-- Records one analytics event. Every field is clamped server-side, so a forged
-- client payload cannot bloat rows or inject oversized values.
create or replace function public.track_event(
  p_path              text,
  p_event_name        text default 'page_view',
  p_session_id        uuid default null,
  p_referrer_host     text default null,
  p_language          text default null,
  p_screen_resolution text default null,
  p_device_type       text default null,
  p_os                text default null,
  p_browser           text default null,
  p_geo_country       text default null,
  p_geo_region        text default null,
  p_geo_city          text default null,
  p_visitor_hash      text default null,
  p_metadata          jsonb default '{}'::jsonb
)
returns void
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_path     text := public.clean_text(p_path, 512);
  v_event    text := coalesce(public.clean_text(p_event_name, 64), 'page_view');
  v_metadata jsonb := coalesce(p_metadata, '{}'::jsonb);
begin
  -- Paths must look like site paths. Anything else is a forged payload.
  if v_path is null or v_path !~ '^/' then
    return;
  end if;

  if jsonb_typeof(v_metadata) <> 'object' or octet_length(v_metadata::text) > 4096 then
    v_metadata := '{}'::jsonb;
  end if;

  -- 240 events per hour per visitor is far above real browsing and far below
  -- what a flood would need to be useful.
  if p_visitor_hash is not null
     and not public.consume_rate_limit('analytics:' || p_visitor_hash, 240, interval '1 hour') then
    return;
  end if;

  insert into public.analytics (
    path, event_name, session_id, referrer_host, language, screen_resolution,
    device_type, os, browser, geo_country, geo_region, geo_city,
    visitor_hash, metadata
  )
  values (
    v_path,
    v_event,
    p_session_id,
    public.clean_text(p_referrer_host, 255),
    public.clean_text(p_language, 35),
    public.clean_text(p_screen_resolution, 24),
    public.clean_text(p_device_type, 32),
    public.clean_text(p_os, 64),
    public.clean_text(p_browser, 64),
    public.clean_text(p_geo_country, 8),
    public.clean_text(p_geo_region, 64),
    public.clean_text(p_geo_city, 96),
    public.clean_text(p_visitor_hash, 64),
    v_metadata
  );
end;
$$;

revoke all on function public.track_event(text, text, uuid, text, text, text, text, text, text, text, text, text, text, jsonb) from public;
grant execute on function public.track_event(text, text, uuid, text, text, text, text, text, text, text, text, text, text, jsonb) to anon, authenticated, service_role;

-- Accepts a contact form submission. Returns a status string rather than raising,
-- so the caller can respond uniformly and never leak which check failed.
create or replace function public.submit_contact_message(
  p_name          text,
  p_message       text,
  p_email         text default null,
  p_referrer_host text default null,
  p_visitor_hash  text default null
)
returns text
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_name    text := public.clean_text(p_name, 120);
  v_email   text := lower(public.clean_text(p_email, 254));
  -- Newlines and tabs survive (messages are multi-line); every other control
  -- character is stripped.
  v_message text := left(
    btrim(regexp_replace(coalesce(p_message, ''),
                         '[\u0000-\u0008\u000B\u000C\u000E-\u001F\u007F-\u009F]', '', 'g')),
    5000
  );
begin
  if v_name is null or char_length(v_message) < 10 then
    return 'invalid';
  end if;

  if v_email is not null and v_email !~* '^[^@\s]+@[^@\s.]+\.[^@\s]+$' then
    return 'invalid';
  end if;

  -- 5 messages per visitor per hour.
  if p_visitor_hash is not null
     and not public.consume_rate_limit('contact:' || p_visitor_hash, 5, interval '1 hour') then
    return 'rate_limited';
  end if;

  -- 50 messages site-wide per hour caps the blast radius of a distributed flood.
  if not public.consume_rate_limit('contact:global', 50, interval '1 hour') then
    return 'rate_limited';
  end if;

  insert into public.contact_messages (name, email, message, referrer_host, visitor_hash)
  values (v_name, v_email, v_message, public.clean_text(p_referrer_host, 255), public.clean_text(p_visitor_hash, 64));

  return 'ok';
end;
$$;

revoke all on function public.submit_contact_message(text, text, text, text, text) from public;
grant execute on function public.submit_contact_message(text, text, text, text, text) to anon, authenticated, service_role;

