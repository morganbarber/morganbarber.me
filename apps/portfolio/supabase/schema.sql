-- morganbarber.me — complete database schema
-- =============================================================================
-- Idempotent. Safe to run repeatedly on a fresh or existing project.
-- Run with:  psql "$SUPABASE_DB_URL" -f supabase/schema.sql
--        or: paste into Supabase Studio → SQL Editor → Run
--
-- SECURITY MODEL
-- --------------
-- The browser and the Next.js server both authenticate as the `anon` role using
-- the publishable/anon key. That key is public by definition, so `anon` is
-- treated as a hostile identity:
--
--   * Public content tables (blog_posts, projects, experience, education,
--     certifications, competitions) grant `anon` SELECT only, and RLS restricts rows to those
--     explicitly marked published.
--   * Write-heavy tables (analytics, contact_messages, rate_limit_buckets) grant
--     `anon` NOTHING. Writes happen exclusively through SECURITY DEFINER
--     functions that validate, clamp and rate-limit their input. `anon` can
--     never read them back, so the tables cannot be used for exfiltration.
--   * Every SECURITY DEFINER function pins `search_path = ''` and uses fully
--     qualified identifiers, which closes the search_path hijack class of
--     privilege escalation.
--   * RLS is enabled on every table. Bypassing it requires the service-role key,
--     which never reaches the browser and is not needed by this app at all.
-- =============================================================================

begin;

-- -----------------------------------------------------------------------------
-- 0. Extensions & baseline grants
-- -----------------------------------------------------------------------------

-- gen_random_uuid() is in pg_catalog from PostgreSQL 13 onward, so no extension
-- is required. It is fully qualified everywhere for search_path safety.

-- Start from "deny by default" on the public schema, then grant back explicitly.
revoke all on schema public from public;
grant usage on schema public to anon, authenticated, service_role;

-- Nothing is granted implicitly to future tables; each grant below is deliberate.
alter default privileges in schema public revoke all on tables from anon, authenticated;
-- PostgreSQL grants EXECUTE on new functions to PUBLIC by default; revoke that
-- so every callable function below is an explicit, deliberate grant.
alter default privileges in schema public revoke all on functions from public, anon, authenticated;
alter default privileges in schema public revoke all on sequences from anon, authenticated;

