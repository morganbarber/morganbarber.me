-- Analytics rows past 180 days have no value and only grow the breach surface.
create or replace function public.prune_old_data()
returns void
language plpgsql
security definer
set search_path = ''
as $$
begin
  delete from public.analytics
   where created_at < timezone('utc', now()) - interval '180 days';

  delete from public.rate_limit_buckets
   where updated_at < timezone('utc', now()) - interval '2 days';
end;
$$;

revoke all on function public.prune_old_data() from public, anon, authenticated;
grant execute on function public.prune_old_data() to service_role;

-- Schedule it if pg_cron is available (Supabase: Database → Extensions → pg_cron).
do $$
begin
  if exists (select 1 from pg_extension where extname = 'pg_cron') then
    perform cron.schedule(
      'prune-old-data',
      '30 3 * * *',
      $cron$select public.prune_old_data();$cron$
    );
  end if;
exception when others then
  raise notice 'pg_cron not scheduled: %', sqlerrm;
end;
$$;

-- -----------------------------------------------------------------------------
-- 10. Resource limits on the public roles
-- -----------------------------------------------------------------------------
-- RLS says which rows the publishable key may see; it says nothing about how
-- many, or for how long a query may run. Without these, `select=*` with no
-- limit returns the whole table, and a pathological filter can hold a
-- connection for as long as Postgres allows.
--
-- PostgREST truncates results above db_max_rows and reports it in Content-Range.
-- statement_timeout cancels the statement without dropping the connection.
-- service_role is left alone: the admin dashboard's aggregation and the
-- retention job legitimately run longer.

alter role anon set pgrst.db_max_rows = '500';
alter role anon set statement_timeout = '5s';
alter role anon set idle_in_transaction_session_timeout = '10s';

alter role authenticated set pgrst.db_max_rows = '1000';
alter role authenticated set statement_timeout = '10s';
alter role authenticated set idle_in_transaction_session_timeout = '30s';

-- The schema layout is free reconnaissance for anyone probing the API.
