-- -----------------------------------------------------------------------------
-- 6. Row Level Security
-- -----------------------------------------------------------------------------

do $$
declare
  t text;
begin
  foreach t in array array[
    'blog_posts', 'projects', 'experience', 'education', 'certifications', 'competitions',
    'analytics', 'contact_messages', 'rate_limit_buckets'
  ]
  loop
    execute format('alter table public.%I enable row level security', t);
    -- NOTE: RLS is enabled but deliberately NOT forced. FORCE would also apply
    -- the policies to the table owner, which would block both the SECURITY
    -- DEFINER write functions in section 8 and ordinary admin seeding, while
    -- protecting against nothing that matters here -- the threat model is a
    -- leaked public anon key, and `anon` is stopped by the combination of
    -- zero table grants (section 7) and zero matching policies below.
    execute format('alter table public.%I no force row level security', t);
  end loop;
end;
$$;

